// Helper to convert raw units into full game unit models with initial customization
export function initializeUnits(): Unit[] {
  return RAW_UNITS_DATA.map((raw) => {
    const vType = determineVehicleType(raw);
    const heroCat = getHeroCategory({ ...raw, vehicleType: vType });
    const pilot = getPilotForUnit(raw.id, raw.role, raw.country, raw.name, false);

    return {
      ...raw,
      maxHp: raw.hp,
      vehicleType: vType,
      heroCategory: heroCat,
      pilot,
      countryName: COUNTRY_NAMES[raw.country]?.name || raw.country,
      unlocked: raw.unlockedByDefault ?? (raw.unlockCostWarBonds === 0),
      upgradeLevel: 1,
      customization: {
        ammoType: 'APFSDS Kinetic',
        armorMod: 'Standard Steel',
        opticsMod: 'Iron Sights & Standard Optics',
        stance: 'Aggressive Assault',
      },
    };
  });
}
