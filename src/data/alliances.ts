/**
 * Generate a realistic roster of 100 members:
 * - 1 Admiral (Leader)
 * - Up to 10 Colonels (Planning & Tasks Staff)
 * - Remaining are Lieutenants
 */
export function generateAllianceMembers(
  allianceTag: string,
  admiralCallsign: string,
  admiralCountry: CountryCode,
  includePlayerAs?: { rank: AllianceRank; callsign: string; country: CountryCode }
): AllianceMember[] {
  const members: AllianceMember[] = [];
  const now = new Date();

  // 1. The Admiral (1 Leader)
  const isPlayerAdmiral = includePlayerAs?.rank === 'Admiral';
  members.push({
    id: `mem-${allianceTag}-admiral`,
    callsign: isPlayerAdmiral ? includePlayerAs.callsign : admiralCallsign,
    rank: 'Admiral',
    country: isPlayerAdmiral ? includePlayerAs.country : admiralCountry,
    combatPower: Math.floor(Math.random() * 4000) + 28000, // 28k - 32k power
    assignedRole: 'Supreme Battlegroup Commander & Operations Director',
    joinedDate: '2025-11-15',
    onlineStatus: 'ONLINE',
    contributionPoints: 12540,
    tasksCompleted: 48,
    isPlayer: isPlayerAdmiral,
  });

  // 2. Up to 10 Colonels
  const colonelsCount = 10;
  let playerAssigned = isPlayerAdmiral;

  for (let i = 1; i <= colonelsCount; i++) {
    const isPlayerCol = !playerAssigned && includePlayerAs?.rank === 'Colonel' && i === 1;
    if (isPlayerCol) playerAssigned = true;

    const callsign = isPlayerCol
      ? includePlayerAs.callsign
      : CALLSIGNS_POOL[(i * 3) % CALLSIGNS_POOL.length] + `_Col`;
    const country = isPlayerCol ? includePlayerAs.country : COUNTRIES_POOL[i % COUNTRIES_POOL.length];

    members.push({
      id: `mem-${allianceTag}-col-${i}`,
      callsign,
      rank: 'Colonel',
      country,
      combatPower: Math.floor(Math.random() * 3500) + 23000, // 23k - 26.5k
      assignedRole: ROLES_POOL[i % ROLES_POOL.length],
      joinedDate: '2025-12-01',
      onlineStatus: i % 3 === 0 ? 'IN_COMBAT' : i % 2 === 0 ? 'DEPLOYED' : 'ONLINE',
      contributionPoints: Math.floor(Math.random() * 4000) + 6500,
      tasksCompleted: Math.floor(Math.random() * 15) + 20,
      isPlayer: isPlayerCol,
    });
  }

  // 3. The Lieutenants (remaining 89 members to total 100!)
  const lieutenantsCount = 100 - members.length;
  for (let i = 1; i <= lieutenantsCount; i++) {
    const isPlayerLt = !playerAssigned && includePlayerAs?.rank === 'Lieutenant' && i === 1;
    if (isPlayerLt) playerAssigned = true;

    const baseCallsign = CALLSIGNS_POOL[(i + 15) % CALLSIGNS_POOL.length];
    const callsign = isPlayerLt
      ? includePlayerAs.callsign
      : `${baseCallsign}_${100 + i}`;
    const country = isPlayerLt ? includePlayerAs.country : COUNTRIES_POOL[(i * 2) % COUNTRIES_POOL.length];

    // Varied statuses
    const statusRoll = i % 5;
    const onlineStatus =
      statusRoll === 0 ? 'OFFLINE' : statusRoll === 1 ? 'IN_COMBAT' : statusRoll === 2 ? 'DEPLOYED' : 'ONLINE';

    members.push({
      id: `mem-${allianceTag}-lt-${i}`,
      callsign,
      rank: 'Lieutenant',
      country,
      combatPower: Math.floor(Math.random() * 6000) + 14000, // 14k - 20k
      assignedRole: ROLES_POOL[(i + 3) % ROLES_POOL.length],
      joinedDate: `2026-0${(i % 3) + 1}-1${(i % 9)}`,
      onlineStatus,
      contributionPoints: Math.floor(Math.random() * 3000) + 800,
      tasksCompleted: Math.floor(Math.random() * 10) + 2,
      isPlayer: isPlayerLt,
    });
  }

  return members;
}

