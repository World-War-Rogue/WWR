/**
 * Composite Leaderboard Scoring Formula:
 * Combines 40% Total Combat Power, 35% Season Event Points, and 25% Territorial Control.
 */
export function calculateAllianceCompositeScore(
  totalCombatPower: number,
  eventScore: number,
  sectorsControlled: number,
  totalTheaterSectors: number = 36
): number {
  // Normalize Combat Power against 2,500,000 max (weight: 4000 pts)
  const powerScore = Math.min(4000, (totalCombatPower / 2500000) * 4000);
  // Normalize Event Points against 500,000 max (weight: 3500 pts)
  const eventPointScore = Math.min(3500, (eventScore / 500000) * 3500);
  // Normalize Territorial control against total theater sectors (weight: 2500 pts)
  const territoryScore = Math.min(2500, (sectorsControlled / totalTheaterSectors) * 2500);

  return Math.round(powerScore + eventPointScore + territoryScore);
}

/**
 * Helper to build the controlled sectors list for an alliance from the master theater sectors
 */
export function extractControlledSectors(allianceTag: string): ControlledSectorInfo[] {
  return INITIAL_THEATER_SECTORS
    .filter((s) => s.controllingAllianceTag === allianceTag)
    .map((s) => ({
      sectorId: s.id,
      name: s.name,
      type: s.type,
      controlLevel: s.defenseStatus === 'FORTIFIED' ? 3 : s.defenseStatus === 'SECURE' ? 2 : 1,
      garrisonRating: s.garrisonRating,
      defenseStatus: s.defenseStatus === 'NEUTRAL' ? 'SECURE' : s.defenseStatus,
      buffYield: s.buffYield,
      assignedColonelCallsign: s.assignedColonelCallsign,
    }));
}

/**
 * Helper to compute hourly yields for an alliance from its controlled sectors
 */
export function calculateSectorYields(sectors: ControlledSectorInfo[]) {
  const matchingMasterSectors = INITIAL_THEATER_SECTORS.filter((s) =>
    sectors.some((cs) => cs.sectorId === s.id)
  );

  return matchingMasterSectors.reduce(
    (acc, s) => ({
      fuel: acc.fuel + s.hourlyYield.fuel,
      munitions: acc.munitions + s.hourlyYield.munitions,
      alloy: acc.alloy + s.hourlyYield.alloy,
      warBonds: acc.warBonds + s.hourlyYield.warBonds,
    }),
    { fuel: 0, munitions: 0, alloy: 0, warBonds: 0 }
  );
}

